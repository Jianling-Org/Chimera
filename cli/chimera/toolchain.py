# build never depends on the user's global git configuration.
GIT_AM_IDENTITY = (
    "-c", "user.name=Chimera Patch Builder",
    "-c", "user.email=chimera@example.invalid",
)

COMPILER_SHIM_BIN_DIR = Path.home() / ".chimera" / "bin"


def install_compiler_shims() -> None:
    """Install ~/.chimera/bin/{clang,clang++} decision-driven wrappers.

    CMake requires a single executable path for CMAKE_C_COMPILER and cannot
    carry arguments, so the chimera-pkg llvm subcommand is exposed as real
    executables here.  The shims exec the installed `chimera-pkg` entry point,
    which resolves the patched clang from the toolchain prefix itself.
    """

    bin_dir = COMPILER_SHIM_BIN_DIR
    bin_dir.mkdir(parents=True, exist_ok=True)
    entry = shutil.which("chimera-pkg") or "chimera-pkg"
    for name, extra in (("clang", ""), ("clang++", "--cxx")):
        shim = bin_dir / name
        content = (
            "#!/usr/bin/env bash\n"
            "# generated by `chimera-dev toolchain build llvm-plugin`; "
            "re-run that target to regenerate\n"
            f'exec "{entry}" llvm {extra} -- "$@"\n'
        )
        shim.write_text(content, encoding="utf-8")
        shim.chmod(0o755)


