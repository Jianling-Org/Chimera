def _step(index: int, total: int, label: str) -> None:
    print(f"========== [{index}/{total}] {label} ==========", flush=True)


def _run(command: list[str], *, cwd: Path | None = None) -> None:
    """Stream one external command; convert failures to RuntimeError."""
    display = " ".join(str(part) for part in command)
    print(f"$ {display}", flush=True)
    try:
        result = subprocess.run(
            command,
            cwd=str(cwd) if cwd is not None else None,
            text=True,
        )
    except FileNotFoundError as error:
        raise RuntimeError(f"required tool not found: {command[0]}") from error
    if result.returncode != 0:
        raise RuntimeError(
            f"command failed (exit {result.returncode}): {display}"
        )


def _git_ok(llvm_src: Path, *arguments: str) -> subprocess.CompletedProcess[str]:
    return subprocess.run(
        ["git", "-C", str(llvm_src), *arguments],
        capture_output=True,
        text=True,
    )


def _llvm_git_path(llvm_src: Path, name: str) -> Path:
    result = _git_ok(llvm_src, "rev-parse", "--git-path", name)
    if result.returncode != 0:
        return llvm_src / ".git" / name
    raw = result.stdout.strip()
    if not raw:
        return llvm_src / ".git" / name
    path = Path(raw)
    return path if path.is_absolute() else llvm_src / path


def _llvm_state_path(llvm_src: Path) -> Path:
    return _llvm_git_path(llvm_src, "chimera-patched-llvm-state.json")


def _llvm_am_in_progress(llvm_src: Path) -> bool:
    return any(
        _llvm_git_path(llvm_src, marker).exists()
        for marker in ("rebase-apply", "rebase-merge")
    )


def _toolchain_clean_hint(llvm_src: Path, build_root: Path | None) -> str:
    command = f"chimera-dev toolchain clean patched-llvm --llvm-src {llvm_src}"
    if build_root is not None:
        command += f" --build-root {build_root}"
    return command


@contextmanager
def _llvm_operation_lock(llvm_src: Path):
    """Hold an OS lock that is released automatically on process exit."""

    if not llvm_src.is_dir() or _git_ok(llvm_src, "rev-parse", "--git-dir").returncode != 0:
        yield
        return
    lock_path = _llvm_git_path(llvm_src, "chimera-patched-llvm.lock")
    lock_path.parent.mkdir(parents=True, exist_ok=True)
    with lock_path.open("a+b") as stream:
        stream.seek(0)
        stream.write(b"0")
        stream.flush()
        stream.seek(0)
        unlock = None
        try:
            try:
                import fcntl

                fcntl.flock(stream.fileno(), fcntl.LOCK_EX | fcntl.LOCK_NB)
                unlock = lambda: fcntl.flock(stream.fileno(), fcntl.LOCK_UN)
            except ImportError:
                import msvcrt

                msvcrt.locking(stream.fileno(), msvcrt.LK_NBLCK, 1)
                unlock = lambda: msvcrt.locking(stream.fileno(), msvcrt.LK_UNLCK, 1)
        except (BlockingIOError, OSError) as error:
            raise ValueError(
                f"another Chimera operation is using the LLVM checkout: {llvm_src}"
            ) from error
        try:
            yield
        finally:
            if unlock is not None:
                unlock()


def _require_clean_llvm_checkout(
    llvm_src: Path, *, build_root: Path | None = None
) -> None:
    if not llvm_src.is_dir():
        raise ValueError(f"LLVM source directory does not exist: {llvm_src}")
    check = _git_ok(llvm_src, "rev-parse", "--git-dir")
    if check.returncode != 0:
        raise ValueError(f"{llvm_src} is not a git checkout of {LLVM_TAG}")
    tags = _git_ok(llvm_src, "tag", "--list", LLVM_TAG)
    if not tags.stdout.strip():
        raise ValueError(f"{llvm_src} has no tag {LLVM_TAG}")
    state_path = _llvm_state_path(llvm_src)
    if state_path.is_file() or state_path.with_suffix(".tmp").is_file() or _llvm_am_in_progress(llvm_src):
        raise ValueError(
            f"{llvm_src} has an interrupted Chimera LLVM build; run the explicit "
            f"cleanup command: {_toolchain_clean_hint(llvm_src, build_root)}"
        )
    head = _git_ok(llvm_src, "rev-parse", "HEAD")
    # Annotated release tags have their own object ID; compare the commit.
    tag = _git_ok(llvm_src, "rev-parse", f"{LLVM_TAG}^{{commit}}")
    if head.returncode == 0 and tag.returncode == 0 and head.stdout.strip() != tag.stdout.strip():
        raise ValueError(
            f"{llvm_src} is not at pristine {LLVM_TAG}; run the explicit cleanup "
            f"command: {_toolchain_clean_hint(llvm_src, build_root)}"
        )
    status = _git_ok(llvm_src, "status", "--porcelain")
    if status.stdout.strip():
        raise ValueError(
            f"{llvm_src} has uncommitted changes; refusing to checkout/apply patches; "
            f"if this is an interrupted build, run {_toolchain_clean_hint(llvm_src, build_root)}"
        )


def _require_llvm_cmake_dir(llvm_prefix: Path) -> Path:
    llvm_dir = llvm_prefix / "lib" / "cmake" / "llvm"
    if not llvm_dir.is_dir():
        raise ValueError(
            f"patched LLVM not found at {llvm_prefix}; run "
            "'chimera-dev toolchain build patched-llvm' first"
        )
    return llvm_dir


def _require_svf_cmake_dir(svf_prefix: Path) -> Path:
    svf_dir = svf_prefix / "lib" / "cmake" / "SVF"
    if not svf_dir.is_dir():
        raise ValueError(
            f"SVF library not found at {svf_prefix}; run "
            "'chimera-dev toolchain build svf' first"
        )
    return svf_dir


def _require_clean_svf_checkout(svf_src: Path) -> None:
    if not svf_src.is_dir():
        raise ValueError(f"SVF source directory does not exist: {svf_src}")
    check = _git_ok(svf_src, "rev-parse", "--git-dir")
    if check.returncode != 0:
        raise ValueError(f"{svf_src} is not a git checkout of {SVF_TAG}")
    present = _git_ok(svf_src, "cat-file", "-e", f"{SVF_COMMIT}^{{commit}}")
    if present.returncode != 0:
        raise ValueError(
            f"{svf_src} does not contain the pinned commit {SVF_COMMIT} "
            f"({SVF_TAG}); fetch it first"
        )
    status = _git_ok(svf_src, "status", "--porcelain")
    if status.stdout.strip():
        raise ValueError(
            f"{svf_src} has uncommitted changes; refusing to checkout {SVF_TAG}"
        )


# Chimera consumes only these LLVM tools; everything else is skipped in the
# default (minimal) build. Library dependencies are pulled in automatically.
# llvm-tblgen is not consumed by Chimera directly, but downstream export sets
# (SVF's SVFTargets.cmake) reference it and it is built anyway as part of
# building LLVM itself.
# lld is needed by downstream LTO links (the examples' svf/full llama.cpp
# variants link with -fuse-ld=lld -fpass-plugin=...).
# llvm-readelf is an add_llvm_tool_symlink() alias of llvm-readobj: the real
# binary is llvm-readobj, which must be built and installed alongside or the
# installed bin/llvm-readelf dangles.  llvm-objdump is needed by the plugin
# test suites (stackobject run.sh and svf tests disassemble linked ELFs to
# derive expected instruction VAs).
MINIMAL_LLVM_TARGETS = (
    "clang", "opt", "llc", "lld", "llvm-readobj", "llvm-readelf", "llvm-tblgen",
    "llvm-objdump",
)

# Install components covering the tools above plus what downstream consumers
# (SVF, Chimera plugins) need from find_package(LLVM).  llvm-readobj must
# precede llvm-readelf so the symlink target exists when it is created.
MINIMAL_LLVM_TOOL_COMPONENTS = (
    "clang",
    "clang-resource-headers",
    "opt",
    "llc",
    "lld",
    "llvm-readobj",
    "llvm-readelf",
    "llvm-tblgen",
    "llvm-objdump",
)
MINIMAL_LLVM_BASE_COMPONENTS = ("llvm-headers", "cmake-exports")

# Binaries each tool component must deliver into <prefix>/bin; verified after
# a minimal install so a skipped/mismatched component fails at the source
# instead of surfacing in a downstream script.
EXPECTED_TOOL_BINARIES = {
    "clang": ("clang", "clang++"),
    "opt": ("opt",),
    "llc": ("llc",),
    "lld": ("ld.lld",),
    "llvm-readobj": ("llvm-readobj",),
    "llvm-readelf": ("llvm-readelf",),
    "llvm-tblgen": ("llvm-tblgen",),
    "llvm-objdump": ("llvm-objdump",),
}


def _llvm_library_components(llvm_build: Path) -> list[str]:
    """Map actually-built static archives to their CMake install components."""
    return [
        archive.stem.removeprefix("lib")
        for archive in sorted(llvm_build.glob("lib/libLLVM*.a"))
    ]


def _has_install_component(scripts: list[str], component: str) -> bool:
    marker = f'"{component}"'
    return any(marker in script for script in scripts)


def _sanitize_cmake_exports(prefix: Path) -> None:
    """Strip missing-file existence checks from installed CMake export sets.

    Export sets (LLVMExports.cmake, ClangTargets.cmake, SVFTargets.cmake,
    ...) reference every target in the export set, but a selective install
    may not produce all of them; the trailing verification loop then aborts
    find_package() on the first missing archive/tool.  Dropping the check
    leaves unused imported targets harmless: libraries must genuinely exist
    (they enter link lines — enforced by the post-install archive check),
    while tools never do.
    """
    marker = "# Loop over all imported files and verify that they actually exist"
    trailer = "unset(_cmake_import_check_targets)"
    cmake_root = prefix / "lib" / "cmake"
    if not cmake_root.is_dir():
        return
    for script in sorted(cmake_root.rglob("*.cmake")):
        text = script.read_text(encoding="utf-8", errors="ignore")
        if marker not in text:
            continue
        head, _, rest = text.partition(marker)
        _, found, tail = rest.partition(trailer)
        if not found:
            print(f"warning: exports check block not terminated in {script}")
            continue
        script.write_text(
            head
            + "# Chimera: existence checks stripped (minimal install)\n"
            + tail,
            encoding="utf-8",
        )
        print(f"sanitized exports file: {script}")


def _install_llvm_components(llvm_build: Path, llvm_prefix: Path) -> None:
    # Component-aware install: a full `cmake --install` would reference files
    # of tools that the minimal build intentionally skipped and fail.
    install_scripts = [
        path.read_text(encoding="utf-8", errors="ignore")
        for path in llvm_build.rglob("cmake_install.cmake")
    ]
    components = [
        *MINIMAL_LLVM_TOOL_COMPONENTS,
        *MINIMAL_LLVM_BASE_COMPONENTS,
        *_llvm_library_components(llvm_build),
    ]
    installed: list[str] = []
    for component in components:
        if not _has_install_component(install_scripts, component):
            print(f"skip install component (not registered): {component}")
            continue
        _run([
            "cmake", "--install", str(llvm_build),
            "--prefix", str(llvm_prefix),
            "--component", component,
        ])
        installed.append(component)
    # Invariant: every built archive must reach the prefix.  A silently
    # skipped library component resurfaces much later as a find_package()
    # failure in SVF/the plugins — fail here instead, at the source.
    missing = [
        archive.name
        for archive in sorted(llvm_build.glob("lib/libLLVM*.a"))
        if not (llvm_prefix / "lib" / archive.name).is_file()
    ]
    if missing:
        raise RuntimeError(
            "built LLVM libraries missing from the install prefix: "
            + ", ".join(missing)
            + "; their install components were not registered — rerun with "
              "--full or extend the component mapping"
        )
    # Same invariant for tool binaries (e.g. llvm-readelf is a symlink whose
    # llvm-readobj target an incomplete component list would leave dangling).
    missing_tools = [
        binary
        for component in installed
        for binary in EXPECTED_TOOL_BINARIES.get(component, ())
        if not (llvm_prefix / "bin" / binary).exists()
    ]
    if missing_tools:
        raise RuntimeError(
            "LLVM tool binaries missing from the install prefix: "
            + ", ".join(missing_tools)
            + "; their install components were skipped or mismatched — rerun "
              "with --full or extend the component mapping"
        )
    _sanitize_cmake_exports(llvm_prefix)


def _build_all_llvm_libraries(llvm_build: Path) -> None:
    """Build every ``lib/libLLVM*.a`` the configured build can produce.

    Downstream export sets (e.g. SVF's SVFTargets.cmake) bake the transitive
    closure of LLVM's exported link interfaces into their install-time
    checks.  A library the minimal tool build skips (e.g. LLVMTableGenBasic,
    pulled in through LLVMPasses) then breaks find_package() for SVF and the
    Chimera plugins.  Building all static LLVM libraries — but not the extra
    tools — keeps the install prefix's library set complete.
    """
    query = subprocess.run(
        ["ninja", "-C", str(llvm_build), "-t", "targets", "all"],
        capture_output=True,
        text=True,
    )
    if query.returncode != 0:
        raise RuntimeError(
            f"ninja -t targets failed (exit {query.returncode}): "
            f"{query.stderr.strip()}"
        )
    archives = sorted({
        line.split(":", 1)[0].strip()
        for line in query.stdout.splitlines()
        if line.startswith("lib/libLLVM")
        and line.split(":", 1)[0].strip().endswith(".a")
    })
    missing = [
        archive for archive in archives
        if not (llvm_build / archive).is_file()
    ]
    if missing:
        _run(["ninja", "-C", str(llvm_build), *missing])

def build_patched_llvm(
    llvm_src: Path,
    llvm_prefix: Path,
    *,
    build_root: Path | None = None,
    full: bool = False,
) -> None:
    with _llvm_operation_lock(llvm_src):
        _build_patched_llvm(
            llvm_src, llvm_prefix, build_root=build_root, full=full
        )


def _build_patched_llvm(
    llvm_src: Path,
    llvm_prefix: Path,
    *,
    build_root: Path | None = None,
    full: bool = False,
) -> None:
    source_root = toolchain_source_root()
    llvm_build = llvm_build_dir(build_root, llvm_src)
    patches = sorted(source_root.glob("patches/*.patch"))
    if not patches:
        raise ValueError(f"no Chimera patches found under {source_root / 'patches'}")
    _require_clean_llvm_checkout(llvm_src, build_root=build_root)

    state_path = _llvm_state_path(llvm_src)
    state_path.parent.mkdir(parents=True, exist_ok=True)
    state_temp = state_path.with_suffix(".tmp")
    state_temp.write_text(
        json.dumps(
            {
                "schema_version": 1,
                "llvm_tag": LLVM_TAG,
                "source_dir": str(llvm_src.resolve()),
                "build_dir": str(llvm_build.resolve()),
            },
            sort_keys=True,
        )
        + "\n",
        encoding="utf-8",
    )
    os.replace(state_temp, state_path)

    active_error: BaseException | None = None
    try:
        _step(1, 6, "checkout llvmorg-21.1.0")
        _run(["git", "checkout", LLVM_TAG], cwd=llvm_src)

        _step(2, 6, "apply Chimera patches")
        _run(
            ["git", *GIT_AM_IDENTITY, "am", *(str(path) for path in patches)],
            cwd=llvm_src,
        )
        _run(["git", "diff", "--check"], cwd=llvm_src)

        _step(3, 6, "configure LLVM (clang + lld / RISCV)")
        _run([
            "cmake", "-S", str(llvm_src / "llvm"), "-B", str(llvm_build),
            "-G", "Ninja", "-DLLVM_ENABLE_PROJECTS=clang;lld",
            "-DCMAKE_BUILD_TYPE=Release", "-DLLVM_TARGETS_TO_BUILD=RISCV",
            "-DLLVM_INCLUDE_TESTS=OFF", "-DLLVM_INCLUDE_EXAMPLES=OFF",
            "-DLLVM_INCLUDE_BENCHMARKS=OFF",
            f"-DCMAKE_INSTALL_PREFIX={llvm_prefix}",
        ])

        if full:
            _step(4, 6, "build LLVM (full)")
            _run(["ninja", "-C", str(llvm_build)])
        else:
            targets = " ".join(MINIMAL_LLVM_TARGETS)
            _step(4, 6, f"build LLVM (minimal: {targets} + all libLLVM*.a)")
            _run(["ninja", "-C", str(llvm_build), *MINIMAL_LLVM_TARGETS])
            _build_all_llvm_libraries(llvm_build)

        _step(5, 6, f"install LLVM -> {llvm_prefix}")
        if full:
            _run(["cmake", "--install", str(llvm_build)])
        else:
            _install_llvm_components(llvm_build, llvm_prefix)
    except BaseException as error:
        active_error = error
        raise
    finally:
        try:
            if _llvm_am_in_progress(llvm_src):
                _run(["git", *GIT_AM_IDENTITY, "am", "--abort"], cwd=llvm_src)
            _step(6, 6, "restore pristine LLVM source")
            _run(["git", "reset", "--hard", LLVM_TAG], cwd=llvm_src)
            state_path.unlink(missing_ok=True)
            print(
                f"restored {llvm_src} to pristine {LLVM_TAG} "
                f"(toolchain installed under {llvm_prefix})"
            )
        except Exception as cleanup_error:
            if active_error is None:
                raise
            print(f"WARNING: automatic LLVM cleanup failed: {cleanup_error}", file=sys.stderr)


def clean_patched_llvm(
    llvm_src: Path, *, build_root: Path | None = None
) -> None:
    with _llvm_operation_lock(llvm_src):
        _clean_patched_llvm(llvm_src, build_root=build_root)


def _clean_patched_llvm(
    llvm_src: Path, *, build_root: Path | None = None
) -> None:
    """Discard tracked LLVM changes and remove only the recorded build tree."""

    if not llvm_src.is_dir() or _git_ok(llvm_src, "rev-parse", "--git-dir").returncode != 0:
        raise ValueError(f"LLVM source directory is not a Git checkout: {llvm_src}")
    if not _git_ok(llvm_src, "tag", "--list", LLVM_TAG).stdout.strip():
        raise ValueError(f"{llvm_src} has no tag {LLVM_TAG}")
    state_path = _llvm_state_path(llvm_src)
    build_dir = build_root and llvm_build_dir(build_root, llvm_src)
    if state_path.is_file():
        try:
            recorded = json.loads(state_path.read_text(encoding="utf-8"))
            if not isinstance(recorded, dict):
                raise TypeError("record must be a JSON object")
            recorded_source = recorded.get("source_dir")
            if recorded_source is not None:
                recorded_source_path = Path(recorded_source).expanduser().resolve()
                if recorded_source_path != llvm_src.resolve():
                    raise ValueError(
                        "recorded LLVM source does not match the requested checkout"
                    )
            build_dir = Path(recorded["build_dir"])
        except (OSError, KeyError, TypeError, json.JSONDecodeError) as error:
            raise ValueError(f"invalid LLVM build record: {state_path}") from error
    if build_dir is None:
        build_dir = llvm_build_dir(None, llvm_src)
    source_real = llvm_src.resolve()
    build_real = build_dir.resolve(strict=False)
    # Build records are written by Chimera, but they survive an interrupted
    # process and are therefore untrusted input at cleanup time.  The builder
    # only ever records the conventional ``<root>/llvm`` directory (or the
    # legacy source-local ``build_patched`` directory); reject arbitrary
    # paths before invoking a recursive delete.  Also reject anything inside
    # Git metadata and the checkout itself, while allowing the intended
    # source-local build_patched sibling.
    if build_real.name not in {"llvm", "build_patched"}:
        raise ValueError(
            f"refusing to remove unrecognized LLVM build directory: {build_real}"
        )
    git_real = (source_real / ".git").resolve(strict=False)
    if (
        build_real == source_real
        or build_real == git_real
        or git_real in build_real.parents
    ):
        raise ValueError(f"refusing to remove unsafe LLVM build directory: {build_real}")
    if _llvm_am_in_progress(llvm_src):
        _run(["git", *GIT_AM_IDENTITY, "am", "--abort"], cwd=llvm_src)
    _run(["git", "reset", "--hard", LLVM_TAG], cwd=llvm_src)
    if build_dir.exists() or build_dir.is_symlink():
        if build_dir.is_symlink():
            raise ValueError(f"refusing to remove symlinked LLVM build directory: {build_dir}")
        if not build_dir.is_dir():
            raise ValueError(f"refusing to remove non-directory LLVM build path: {build_dir}")
        shutil.rmtree(build_dir)
    state_path.unlink(missing_ok=True)
    state_path.with_suffix(".tmp").unlink(missing_ok=True)
    print(f"cleaned LLVM source and build directory: {build_dir}")


def build_svf(
    svf_src: Path,
    llvm_prefix: Path,
    svf_prefix: Path,
    *,
    build_root: Path | None = None,
) -> None:
    """Build and install the SVF library itself from a source checkout.

    Like LLVM, the SVF version is pinned: the checkout is forced to
    SVF_COMMIT (tag SVF-3.3) before building rather than adapting to
    whatever version happens to be checked out. Chimera SVF patches
    (svf-patches/*.patch under the toolchain source root, if any) are
    applied after the checkout, and the tree is restored to the pristine
    pinned commit after the install.
    """
    if not (svf_src / "CMakeLists.txt").is_file():
        raise ValueError(
            f"SVF source checkout not found at {svf_src}; run "
            "'git submodule update --init third_party/SVF' or pass --svf-dir "
            "pointing to an SVF source checkout"
        )
    llvm_dir = _require_llvm_cmake_dir(llvm_prefix)
    build = svf_build_dir(build_root, svf_src)
    try:
        patches = sorted(toolchain_source_root().glob("svf-patches/*.patch"))
    except FileNotFoundError:
        # Toolchain source bundle not installed (e.g. slim test layout):
        # an upstream-pure SVF build is still legitimate.
        patches = []

    _step(1, 5, f"checkout {SVF_TAG}")
    _require_clean_svf_checkout(svf_src)
    _run(["git", "checkout", SVF_COMMIT], cwd=svf_src)

    _step(2, 5, f"apply Chimera SVF patches ({len(patches)} found)")
    if patches:
        _run(["git", "apply", *(str(path) for path in patches)], cwd=svf_src)
        _run(["git", "diff", "--check"], cwd=svf_src)

    _step(3, 5, "configure SVF library")
    _run([
        "cmake", "-S", str(svf_src), "-B", str(build),
        "-G", "Ninja",
        "-DCMAKE_BUILD_TYPE=Release",
        # SVF defaults SVF_WARN_AS_ERROR=ON; newer compilers keep adding
        # warnings that break the pinned SVF source (e.g. GCC 15 unused
        # variable diagnostics). Chimera consumes SVF as a library, so
        # upstream's developer-facing strictness is disabled for a
        # deterministic build.
        "-DSVF_WARN_AS_ERROR=OFF",
        f"-DLLVM_DIR={llvm_dir}",
        f"-DCMAKE_INSTALL_PREFIX={svf_prefix}",
    ])

    _step(4, 5, "build SVF library")
    _run(["cmake", "--build", str(build)])

    _step(5, 5, f"install SVF -> {svf_prefix}")
    _run(["cmake", "--install", str(build)])
    # SVF's export set references LLVM artifacts outside SVF's control (e.g.
    # the llvm-tblgen executable); strip the same existence checks so
    # find_package(SVF) does not fail on non-link-critical references.
    _sanitize_cmake_exports(svf_prefix)
    if patches:
        _run(["git", "reset", "--hard", SVF_COMMIT], cwd=svf_src)
        print(f"restored {svf_src} to pristine {SVF_TAG}")
    print(f"SVF_DIR = {svf_prefix} (lib/cmake/SVF)")


def build_llvm_plugin(
    llvm_prefix: Path,
    svf_prefix: Path,
    plugin_prefix: Path,
    plugins: tuple[str, ...] = ALL_PLUGINS,
    *,
    build_root: Path | None = None,
) -> None:
    """Build the selected Chimera LLVM plugins (default: all)."""
    unknown = set(plugins) - set(PLUGIN_TARGETS)
    if unknown:
        raise ValueError(
            f"unknown plugins: {sorted(unknown)}; "
            f"choose from {sorted(PLUGIN_TARGETS)}"
        )
    llvm_dir = _require_llvm_cmake_dir(llvm_prefix)
    options: list[str] = []
    targets: list[str] = []
    for name, (option, target) in PLUGIN_TARGETS.items():
        selected = name in plugins
        options.append(f"-D{option}={'ON' if selected else 'OFF'}")
        if selected:
            targets.append(target)
    svf_dir = None
    if "function-pointer" in plugins:
        svf_dir = _require_svf_cmake_dir(svf_prefix)
    source_root = toolchain_source_root()
    build = plugin_build_dir(build_root, source_root)

    label = " + ".join(targets)
    _step(1, 3, f"configure Chimera plugins ({label})")
    configure = [
        "cmake", "-S", str(source_root / "plugins"), "-B", str(build),
        f"-DLLVM_DIR={llvm_dir}",
        "-DBUILD_TESTING=ON",
        # 固定 libdir：wrapper 按 lib/chimera/llvm 定位插件，
        # 避免 lib64 发行版上安装位置漂移。
        "-DCMAKE_INSTALL_LIBDIR=lib",
        f"-DCMAKE_INSTALL_PREFIX={plugin_prefix}",
        *options,
    ]
    if svf_dir is not None:
        configure.append(f"-DSVF_DIR={svf_dir}")
    _run(configure)

    _step(2, 3, f"build Chimera plugins ({label})")
    for target in targets:
        _run(["cmake", "--build", str(build), "--target", target])

    _step(3, 3, f"install plugins -> {plugin_prefix}")
    _run(["cmake", "--install", str(build)])
    install_compiler_shims()
    print(f"plugins installed under {plugin_prefix} (lib/chimera/llvm)")
    print(
        f"compiler shims installed under {COMPILER_SHIM_BIN_DIR} "
        "(point CMAKE_C/CXX_COMPILER there to enable decision-driven builds)"
    )


