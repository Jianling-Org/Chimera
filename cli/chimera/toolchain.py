def toolchain_source_root() -> Path:
    # Candidates are probed in order: bundled wheel copy first, then the live
    # checkout (editable install exposes the repository root via the finder).
    override = os.environ.get("CHIMERA_TOOLCHAIN_SOURCE_ROOT")
    if override:
        candidate = Path(override).expanduser().resolve()
        if candidate.joinpath("plugins", "CMakeLists.txt").is_file():
            return candidate
        raise FileNotFoundError(
            "CHIMERA_TOOLCHAIN_SOURCE_ROOT does not contain a Chimera toolchain source bundle"
        )
    root = importlib.resources.files("chimera")
    candidates = [
        Path(str(root.joinpath("toolchain_source"))),
        Path(str(root.joinpath("preprocessing/offline/toolchain/llvm-21.1.0"))),
    ]
    # Editable/source checkouts keep the bundle outside the Python package.
    # Only use that checkout fallback when ``importlib.resources`` really
    # points at this source package; test doubles and installed wheels must
    # still report a missing resource instead of reaching into this checkout.
    package_root = Path(str(root)).resolve()
    if package_root == Path(__file__).resolve().parent:
        candidates.append(
            Path(__file__).resolve().parents[2]
            / "preprocessing" / "offline" / "toolchain" / "llvm-21.1.0"
        )
    for candidate_path in candidates:
        candidate_path = candidate_path.resolve()
        if candidate_path.joinpath("plugins", "CMakeLists.txt").is_file():
            return candidate_path
    raise FileNotFoundError("the Chimera toolchain source bundle is not installed")


def third_party_root() -> Path:
    root = importlib.resources.files("chimera")
    candidates = [
        Path(str(root.joinpath("third_party"))),
    ]
    package_root = Path(str(root)).resolve()
    if package_root == Path(__file__).resolve().parent:
        candidates.append(Path(__file__).resolve().parents[2] / "third_party")
    for candidate in candidates:
        candidate = candidate.resolve()
        if candidate.is_dir():
            return candidate
    raise FileNotFoundError(
        "the Chimera third-party bundle is not installed; install with "
        "CHIMERA_INSTALL_THIRD_PARTY=ON or pass an explicit path"
    )


def toolchain_build_root(explicit: Path | None) -> Path:
    if explicit is not None:
        return explicit
    env = os.environ.get(TOOLCHAIN_BUILD_ENV)
    if env:
        return Path(env)
    return Path.home() / ".chimera" / "toolchain_build"


