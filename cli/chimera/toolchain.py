"""Build the modified LLVM toolchain, SVF, and Chimera plugins from the CLI.

`chimera-dev toolchain build {patched-llvm|svf|llvm-plugin}` is the developer
entry point for building the supported toolchain components:
toolchain construction (patching and building LLVM, building the SVF library
itself, and building the StackObject, FunctionPointer, and VectorGate plugins)
lives in the CLI; application examples remain separate source artifacts.

All artifacts are installed under the toolchain build root (default
``~/.chimera/toolchain_build``) with three subdirectories:

- ``llvm/``    — patched LLVM install prefix (``lib/cmake/llvm``)
- ``svf/``     — SVF library install prefix (``lib/cmake/SVF``)
- ``plugins/`` — Chimera plugin install prefix (``lib/chimera/llvm/*.so``)

Source layout is resolved from the explicit ``CHIMERA_TOOLCHAIN_SOURCE_ROOT``
override or the installed package resources. Application Profiles are not
required for toolchain construction.
"""

